      <p style="max-width:640px;">When Constant found a farm in Costa Rica's lower Savegre Valley in 1997, that idea found a completely different landscape: tropical forest, a warm river, birdlife, small communities, rain, waterfalls — a valley that still worked according to its own rhythm.</p>
      <p style="max-width:640px; font-weight:700; color:#fff;">Rafiki opened in 2002. The safari tents came from the African influence. Everything that happened after that became Costa Rican.</p>
